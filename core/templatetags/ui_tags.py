@register.simple_tag
def icon(name, size=18):
    """Inline SVG icon: {% icon "bug" 20 %}"""
    body = ICONS.get(name, "")
    return mark_safe(
        f'<svg class="icon" width="{int(size)}" height="{int(size)}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true">{body}</svg>'
    )


@register.simple_tag(takes_context=True)
def nav_link(context, key, label, icon_name, url_name):
    """Sidebar link (Bootstrap nav-pill) that is active when `nav` in the context equals `key`."""
    active = " active" if context.get("nav") == key else ""
    return format_html(
        '<a class="nav-link d-flex align-items-center gap-3{}" href="{}">{}<span>{}</span></a>',
        active, reverse(url_name), icon(icon_name, 18), label,
    )

SPRINT_BADGE = {"planned": "bg-primary-subtle text-primary-emphasis", "active": "bg-success-subtle text-success-emphasis",
                "completed": "bg-secondary-subtle text-secondary-emphasis"}


@register.filter
def sprint_badge(value):
    return SPRINT_BADGE.get(value, "bg-secondary-subtle text-secondary-emphasis")

    
