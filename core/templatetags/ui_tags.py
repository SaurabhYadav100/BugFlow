@register.simple_tag(takes_context=True)
def sidebar(context):
    user = context["request"].user
    links = "".join(str(nav_link(context, *item)) for item in NAV.get(user.role_key, NAV["developer"]))
    logout = format_html(
        '<form class="mt-auto" method="post" action="{}"><input type="hidden" name="csrfmiddlewaretoken" value="{}">'
        '<button type="submit" class="nav-link d-flex align-items-center gap-3 w-100">{}<span>Logout</span></button></form>',
        reverse("logout"), get_token(context["request"]), icon("log-out", 18),
    )
    return format_html('<nav class="nav nav-pills flex-column gap-1">{}</nav>{}', mark_safe(links), logout)
