@register.filter
def status_badge(value):
    """{{ issue.status|status_badge }} -> Bootstrap colour classes for a pill badge."""
    return STATUS_BADGE.get(value, "bg-secondary-subtle text-secondary-emphasis")


@register.filter
def priority_badge(value):
    return PRIORITY_BADGE.get(value, "bg-secondary-subtle text-secondary-emphasis")


